// -----------------------------------------------------------------------------
//  Error codes
// -----------------------------------------------------------------------------
enum class Error : std::uint8_t {
    None,
    KeyNotFound,        // state variable is not registered
    AlreadyRegistered,  // add() called for an already registered key
    StorageFull,        // StorageBytes is insufficient
    ListenerFull,       // MaxListeners limit reached
    NullCallback,       // callback is nullptr
    MaxDepth,           // STATE_MAX_DISPATCH_DEPTH reached (recursive dispatch?)
    InDispatch,         // clear() while callbacks are running, including on another core
    NotComparable,      // type has no REFLECT()/operator== and no setComparator()
    NotDefaultConstructible  // addAll(): no default constructor and not registered beforehand
};

inline const char* errorText(Error e) {
    switch (e) {
        case Error::None: return "no error";
        case Error::KeyNotFound: return "state variable not registered";
        case Error::AlreadyRegistered: return "key already registered";
        case Error::StorageFull: return "StorageBytes too small";
        case Error::ListenerFull: return "MaxListeners reached";
        case Error::NullCallback: return "callback is null";
        case Error::MaxDepth: return "maximum callback depth reached";
        case Error::InDispatch: return "not allowed while callbacks are running";
        case Error::NotComparable: return "type is not comparable (REFLECT, operator== or setComparator)";
        case Error::NotDefaultConstructible: return "type has no default constructor: register it first with add(Variable, initialValue)";
    }
    return "?";
}

// -----------------------------------------------------------------------------
//  Result of trySet() / tryUpdate()
// -----------------------------------------------------------------------------
enum class SetStatus : std::uint8_t {
    Error,         // nothing changed; reason is in SetResult::error
    Unchanged,     // equal according to the active comparison -> nothing stored
    StoredSilent,  // float/double within tolerance: stored without notification
    Changed        // changed and stored; active listeners were dispatched
                   // (even when no listeners are registered)
};

inline const char* statusText(SetStatus s) {
    switch (s) {
        case SetStatus::Error: return "error";
        case SetStatus::Unchanged: return "unchanged";
        case SetStatus::StoredSilent: return "stored silently";
        case SetStatus::Changed: return "changed";
    }
    return "?";
}

// This error code belongs to exactly this call, unlike lastErrorCode(), which
// may already have been overwritten by another core or ISR.
struct SetResult {
    SetStatus status;
    Error error;  // Error::None unless status == SetStatus::Error

    bool ok() const { return status != SetStatus::Error; }
    bool changed() const { return status == SetStatus::Changed; }  // same condition returned by set()
    bool stored() const { return status == SetStatus::StoredSilent || status == SetStatus::Changed; }
};

// -----------------------------------------------------------------------------
//  Lock policies
// -----------------------------------------------------------------------------
struct NoLock {
    void lock() {}
    void unlock() {}
};

#if defined(__arm__) && (defined(__ARM_ARCH_6M__) || defined(__ARM_ARCH_7M__) ||    \
                         defined(__ARM_ARCH_7EM__) || defined(__ARM_ARCH_8M_BASE__) || \
                         defined(__ARM_ARCH_8M_MAIN__) || defined(__ARM_ARCH_8_1M_MAIN__))
// Recursive PRIMASK lock. Restores the previous interrupt state.
// Protects against interrupts on the same core only, not against another core.
class IrqLock {
public:
    void lock() {
        std::uint32_t primask;
        __asm volatile("mrs %0, primask" : "=r"(primask));
        __asm volatile("cpsid i" ::: "memory");
        if (depth_++ == 0) saved_ = primask;
    }
    void unlock() {
        if (--depth_ == 0 && !(saved_ & 1u)) __asm volatile("cpsie i" ::: "memory");
    }

private:
    std::uint32_t saved_ = 0;
    std::uint8_t depth_ = 0;
};
#define STATE_HAS_IRQ_LOCK 1
#endif

#ifdef STATE_HAS_PICO_LOCK
// Hardware spinlock with local interrupts disabled; recursive per core.
// Uses one of the SDK striped spinlocks, so no separate claim/init is required
// and the lock is safe to construct as a global object before setup().
//
// Each core owns its own recursion depth and saved IRQ state. A core accesses
// only its own fields; cross-core synchronization is provided exclusively by
// the hardware spinlock. While depth_ > 0, interrupts are disabled on that core,
// so an ISR cannot modify that core's recursion state.
class PicoLock {
public:
    PicoLock() : sl_(spin_lock_instance(next_striped_spin_lock_num())) {}
    void lock() {
        const unsigned core = get_core_num();
        if (depth_[core] != 0) {  // this core already holds the lock
            ++depth_[core];
            return;
        }
        saved_[core] = spin_lock_blocking(sl_);
        depth_[core] = 1;
    }
    void unlock() {
        const unsigned core = get_core_num();
        if (--depth_[core] == 0) spin_unlock(sl_, saved_[core]);
    }

private:
    static constexpr unsigned kCores = NUM_CORES;
    spin_lock_t* sl_;
    std::uint32_t saved_[kCores] = {};
    std::uint8_t depth_[kCores] = {};
};
#endif

#ifdef STATE_HAS_ESP32_LOCK
// ESP-IDF portMUX critical section. Excludes the other core and masks local
// interrupts up to the FreeRTOS critical-section level.
// Critical sections are recursive per core under ESP-IDF.
// The _SAFE variants select task or ISR handling automatically, so the same
// instance can be used from loop(), other tasks and normal ISRs.
// For ESP_INTR_FLAG_IRAM ISRs, all called code and involved types must also be
// IRAM-safe; when in doubt, set a flag in the ISR and access state from a task.
class Esp32Lock {
public:
    Esp32Lock() { portMUX_INITIALIZE(&mux_); }
    void lock() { portENTER_CRITICAL_SAFE(&mux_); }
    void unlock() { portEXIT_CRITICAL_SAFE(&mux_); }

private:
    portMUX_TYPE mux_;
};
#endif


