// true for REFLECT() structs
template <class T>
inline constexpr bool isReflected = detail::IsCoreReflect<std::remove_cv_t<T>>;

// Same comparison rules as the default, but with tolerance for float/double
// members. Useful inside custom comparators, for example:
//   bool motorEqual(const MotorData& a, const MotorData& b) {
//       return reflectstate::approxEqual(a, b, 0.05);
//   }
template <class T>
bool approxEqual(const T& a, const T& b, double tolerance) {
    return detail::equal(a, b, std::fabs(tolerance));
}

namespace detail {
template <class F, class FR>
void visitMember(F& f, FR& fr) {
    if constexpr (!IsComment<FR>) f(fr.key, unwrapField(fr.value));
}
}  // namespace detail

// Iterate over all reflected members: f(const char* name, member&).
// COMMENT("...") entries are skipped. name is the MEMBER/MEMBER_AS key;
// fn()/fx() wrappers are unwrapped so f receives the actual value.
template <class T, class F>
void forEachMember(T& obj, F&& f) {
    using U = std::remove_cv_t<T>;
    static_assert(isReflected<U>, "forEachMember: type has no REFLECT()");
    obj.reflect([&](auto&&... fr) { (detail::visitMember(f, fr), ...); });
}

// -----------------------------------------------------------------------------
//  Typed state variables (STATE_VARIABLES)
// -----------------------------------------------------------------------------
// Every state variable is an empty type carrying both key and value type. This
// lets the compiler infer the return type of state.get(Variable::Speed), which a
// plain enum cannot provide. The underlying enum key is available as
// Variable::Speed.key when needed, for example in a switch.
template <auto K, class T>
struct Var {
    static_assert(std::is_enum<decltype(K)>::value, "Var<K, T>: K must be an enum value");
    using Type = T;
    using Key = decltype(K);
    static constexpr Key key = K;
};

namespace detail {
// Is T a descriptor struct generated by STATE_VARIABLES?
template <class T, class = void>
struct IsVariables : std::false_type {};
template <class T>
struct IsVariables<T, std::void_t<typename T::Id, decltype(T::Id::Count)>>
    : std::is_enum<typename T::Id> {};

// Prevent template argument deduction from this parameter (C++20: std::type_identity_t).
template <class T>
struct TypeIdentity {
    using type = T;
};
template <class T>
using NoDeduce = typename TypeIdentity<T>::type;
}  // namespace detail

