//  https://github.com/Michael-0-sys/ReflectState
//
//  Structs use the same reflection metadata as ReflectJSON and ReflectINI
//  (ReflectCore.h): one description for JSON, INI and state change detection.
//
//      struct MotorData {
//          float power;
//          float current;
//          int   rpm;
//          REFLECT(
//              MEMBER(power, fn(power, 1)),   // fn()/fx() only affect JSON/INI formatting
//              MEMBER(current),              // ReflectState compares the raw float value
//              MEMBER_AS("rpm", rpm)         // custom key names do not affect comparison
//          )
//      };
//
//  State variables and their types are declared once with STATE_VARIABLES.
//  After that, no API call needs an explicit <Type>:
//
//      STATE_VARIABLES(Variable,
//          STATE_VAR(Speed, float),
//          STATE_VAR(Power, uint32_t),
//          STATE_VAR(Motor, MotorData)
//      )
//
//      StateManager<Variable, 256, 8, reflectstate::PicoLock> state;
//
//      state.addAll();                              // register all with initial value T{}
//      state.set(Variable::Power, 750);             // 750 is converted to uint32_t
//      MotorData m = state.get(Variable::Motor);
//      state.onChange(Variable::Speed, [](const float& oldV, const float& newV) { ... });
//
//  A mismatched type, for example an int callback for Speed, is a compile error.
//  Types without REFLECT() are compared with operator==, or with a custom
//  comparator installed through setComparator().
//
//  Target platforms: RP2040/RP2350 (Pico/Pico 2), ESP32/ESP32-S3, Teensy 3.x/4.x,
//  Arduino UNO R4 and PC hosts (unit tests).
//
//  Features:
//  - no heap allocation inside StateManager, no std::map and no std::function
//  - fixed and predictable RAM usage; all storage is part of the object
//  - every state variable may use a different copyable C++ type
//    (add(Var)/get() require a default constructor unless an initial/fallback
//    value is supplied through add(..., initial), tryGet() or getOr())
//  - change detection for REFLECT() structs, std::optional, arrays and operator==
//    (char arrays are compared as strings, matching ReflectJSON/ReflectINI)
//  - multiple listeners per state variable: functions, captureless lambdas,
//    context callbacks and member functions
//  - callbacks may add/remove listeners, remove state variables and call set();
//    nested dispatch depth is limited by STATE_MAX_DISPATCH_DEPTH
//  - optional thread/core/interrupt safety through a lock policy
//  - trySet()/tryUpdate() provide detailed results; setComparator() supports
//    custom comparison rules such as float tolerances inside structs
//  - clear() resets all stored values, listeners, comparators and tolerances
//
//  Template parameters:
//    StateManager<Variable, StorageBytes = 256, MaxListeners = 16,
//                 LockPolicy = reflectstate::NoLock>
//
//      Variable     : descriptor generated by STATE_VARIABLES
//      StorageBytes : shared byte pool for all stored values
//      MaxListeners : maximum listener count across all variables; 0 is allowed
//      LockPolicy   : class providing lock()/unlock(), see "Locking" below
//
//  Errors:
//    Failed calls return false (or a default value for get()) and set
//    lastErrorCode() plus lastError(). The error is sticky: it remains available
//    until clearError() is called or a later error replaces it.
//
//    To report errors when they occur, define this before including ReflectState.h:
//
//        #define STATE_ON_ERROR(msg) Serial.println(msg)
//
//    STATE_ON_ERROR is never called while the manager's lock is held. It runs
//    immediately after the failed operation releases the lock. Inside an explicit
//    scopedLock() block, reporting is deferred until the outer lock is released.
//    If an error occurs in an interrupt, STATE_ON_ERROR runs in that interrupt.
//
//  Locking:
//    reflectstate::NoLock is the default and has no synchronization overhead.
//    Use a lock policy when multiple cores, RTOS tasks or interrupts access the
//    same StateManager.
//
//      reflectstate::NoLock    - single execution context, no ISR access
//      reflectstate::IrqLock   - one Cortex-M core; briefly disables interrupts
//      reflectstate::PicoLock  - RP2040/RP2350 spinlock + local IRQ protection
//      reflectstate::Esp32Lock - ESP32 portMUX, safe for tasks, cores and ISRs
//
//    Custom policies only need void lock() and void unlock(). They must be
//    recursive only when StateManager::lock()/scopedLock() are used explicitly.
//
//    Callbacks normally run without the manager lock held to avoid deadlocks and
//    long critical sections. They receive copies of old/new values. Concurrent
//    set() calls from different cores can therefore be observed in a different
//    callback order than the final storage order.
//
//    Multiple operations can be grouped atomically:
//      { auto g = state.scopedLock(); ... }
//
//    Callbacks triggered inside such an explicit block run while the outer lock
//    remains held, so the chosen lock policy must support recursion.
// =============================================================================

